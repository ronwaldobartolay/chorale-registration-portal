-- Run this once in Supabase Dashboard > SQL Editor.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  full_name text not null,
  zone text,
  category text,
  contact_number text,
  created_at timestamptz not null default now()
);

alter table public.registrations enable row level security;

-- The application uses the server-side Supabase service-role key.
-- Do NOT put that key in browser JavaScript.
-- No public RLS policies are required for this setup.
create index if not exists registrations_full_name_idx on public.registrations (full_name);
create index if not exists registrations_created_at_idx on public.registrations (created_at desc);
